import type { Diagram, DiagramNode, Edge } from "@uml-editor/shared";

/**
 * Escapes special LaTeX characters for text mode.
 */
export function escapeLaTeX(str: string): string {
  if (!str) return "";
  return str
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}

function safeNodeId(id: string): string {
  return "node_" + id.replace(/[^a-zA-Z0-9_]/g, "_");
}

/**
 * Generates high-quality native LaTeX PGF/TikZ vector markup from a Diagram.
 * Perfect for IEEE/ACM papers, university theses (skripsi), and Overleaf.
 */
export function generateTikZ(diagram: Diagram): string {
  const lines: string[] = [];

  lines.push(`% ========================================================`);
  lines.push(`% Generated by UML Flow (Native LaTeX TikZ Exporter)`);
  lines.push(`% Diagram Name: ${diagram.name}`);
  lines.push(`% Diagram Type: ${diagram.type}`);
  lines.push(`% Required LaTeX packages in preamble:`);
  lines.push(`%   \\usepackage{tikz}`);
  lines.push(`%   \\usetikzlibrary{shapes.geometric, arrows.meta, positioning, calc}`);
  lines.push(`% ========================================================`);
  lines.push(``);
  lines.push(`\\begin{tikzpicture}[`);
  lines.push(`    >=Stealth,`);
  lines.push(`    node distance=1.5cm,`);
  lines.push(`    font=\\sffamily,`);
  lines.push(`    % Styles`);
  lines.push(`    flowstart/.style={draw=emerald!80!black, fill=emerald!10, rounded corners=10pt, minimum height=0.8cm, minimum width=2.0cm, align=center, thick},`);
  lines.push(`    flowproc/.style={draw=blue!70!black, fill=blue!5, rectangle, rounded corners=2pt, minimum height=0.9cm, minimum width=2.4cm, align=center, thick},`);
  lines.push(`    flowdecision/.style={draw=orange!80!black, fill=amber!10, diamond, aspect=2, minimum width=2.5cm, align=center, thick},`);
  lines.push(`    flowio/.style={draw=cyan!70!black, fill=cyan!10, trapezium, trapezium left angle=70, trapezium right angle=110, minimum height=0.8cm, align=center, thick},`);
  lines.push(`    umlbox/.style={draw=slate!70!black, fill=white, rectangle, rounded corners=1pt, align=left, inner sep=6pt, thick},`);
  lines.push(`    erdbox/.style={draw=indigo!80!black, fill=indigo!5, rectangle, rounded corners=2pt, align=left, inner sep=6pt, thick},`);
  lines.push(`    baseedge/.style={->, thick, draw=black!75},`);
  lines.push(`    dashededge/.style={->, dashed, thick, draw=black!75},`);
  lines.push(`    inherit/.style={->, thick, draw=black!75, >={Triangle[open, length=6pt, width=6pt]}},`);
  lines.push(`    compose/.style={<{Diamond[fill=black, length=6pt, width=6pt]}-, thick, draw=black!75},`);
  lines.push(`    aggregate/.style={<{Diamond[open, length=6pt, width=6pt]}-, thick, draw=black!75}`);
  lines.push(`]`);
  lines.push(``);

  if (!diagram.nodes || diagram.nodes.length === 0) {
    lines.push(`    % No nodes defined in diagram`);
    lines.push(`    \\node {Empty Diagram};`);
    lines.push(`\\end{tikzpicture}`);
    return lines.join("\n");
  }

  // Calculate coordinates bounds for centering / scaling
  let minX = Infinity;
  let minY = Infinity;
  for (const n of diagram.nodes) {
    const x = n.position?.x ?? 0;
    const y = n.position?.y ?? 0;
    if (x < minX) minX = x;
    if (y < minY) minY = y;
  }
  if (!isFinite(minX)) minX = 0;
  if (!isFinite(minY)) minY = 0;

  lines.push(`    % --- NODES ---`);
  for (const node of diagram.nodes) {
    const nodeId = safeNodeId(node.id);
    const x = (((node.position?.x ?? 0) - minX) / 80).toFixed(2);
    // Y inverted for TikZ coordinate system (Y goes up)
    const y = (-((node.position?.y ?? 0) - minY) / 80).toFixed(2);

    const nodeType = (node.type || "default").toLowerCase();
    const label = escapeLaTeX(node.name || node.id);

    if (diagram.type === "class") {
      // UML Class Node with compartments
      const linesInner: string[] = [];
      const stereotype = (node as any).stereotype || (node.type === "interface" ? "interface" : node.type === "abstract" ? "abstract" : null);
      if (stereotype) {
        linesInner.push(`{\\footnotesize \\textit{\\guillemotleft ${escapeLaTeX(stereotype)} \\guillemotright}}\\\\`);
      }
      linesInner.push(`\\textbf{${label}}`);

      const attrs: any[] = (node as any).attributes || [];
      const methods: any[] = (node as any).methods || [];

      if (attrs.length > 0) {
        linesInner.push(`\\rule{\\linewidth}{0.3pt}`);
        for (const a of attrs) {
          const vis = a.visibility === "private" ? "-" : a.visibility === "protected" ? "#" : "+";
          const aType = a.type ? `: ${escapeLaTeX(a.type)}` : "";
          linesInner.push(`${vis} ${escapeLaTeX(a.name)}${aType}\\\\`);
        }
      }

      if (methods.length > 0) {
        linesInner.push(`\\rule{\\linewidth}{0.3pt}`);
        for (const m of methods) {
          const vis = m.visibility === "private" ? "-" : m.visibility === "protected" ? "#" : "+";
          const ret = m.returnType ? `: ${escapeLaTeX(m.returnType)}` : "";
          linesInner.push(`${vis} ${escapeLaTeX(m.name)}()${ret}\\\\`);
        }
      }

      const content = linesInner.join("\n        ");
      lines.push(`    \\node[umlbox] (${nodeId}) at (${x}, ${y}) {`);
      lines.push(`        ${content}`);
      lines.push(`    };`);
    } else if (diagram.type === "erd") {
      // ERD Entity Node
      const linesInner: string[] = [];
      linesInner.push(`\\textbf{\\textsc{${label}}}`);

      const fields: any[] = (node as any).fields || [];
      if (fields.length > 0) {
        linesInner.push(`\\rule{\\linewidth}{0.3pt}`);
        for (const f of fields) {
          const pkTag = f.isPrimaryKey ? " \\textbf{[PK]}" : f.isForeignKey ? " \\textit{[FK]}" : "";
          const fName = f.isPrimaryKey ? `\\underline{${escapeLaTeX(f.name)}}` : escapeLaTeX(f.name);
          const fType = f.type ? `: ${escapeLaTeX(f.type)}` : "";
          linesInner.push(`${fName}${fType}${pkTag}\\\\`);
        }
      }

      const content = linesInner.join("\n        ");
      lines.push(`    \\node[erdbox] (${nodeId}) at (${x}, ${y}) {`);
      lines.push(`        ${content}`);
      lines.push(`    };`);
    } else {
      // Flowchart / Activity / General Nodes
      let style = "flowproc";
      if (nodeType === "start" || nodeType === "end" || nodeType === "terminal") {
        style = "flowstart";
      } else if (nodeType === "decision") {
        style = "flowdecision";
      } else if (nodeType === "io" || nodeType === "manual-input") {
        style = "flowio";
      }

      lines.push(`    \\node[${style}] (${nodeId}) at (${x}, ${y}) {${label}};`);
    }
  }

  lines.push(``);
  lines.push(`    % --- EDGES ---`);
  if (diagram.edges && diagram.edges.length > 0) {
    for (const edge of diagram.edges) {
      const srcId = safeNodeId(edge.source);
      const tgtId = safeNodeId(edge.target);
      const edgeType = (edge.type || "").toLowerCase();

      let style = "baseedge";
      if (edgeType === "inheritance" || edgeType === "generalization") {
        style = "inherit";
      } else if (edgeType === "composition") {
        style = "compose";
      } else if (edgeType === "aggregation") {
        style = "aggregate";
      } else if (edgeType === "dependency" || edgeType === "dashed") {
        style = "dashededge";
      }

      const labelText = edge.label?.text ? escapeLaTeX(edge.label.text) : "";
      const labelNode = labelText ? ` node[midway, above, font=\\footnotesize] {${labelText}}` : "";

      lines.push(`    \\draw[${style}] (${srcId}) --${labelNode} (${tgtId});`);
    }
  }

  lines.push(`\\end{tikzpicture}`);
  return lines.join("\n");
}
