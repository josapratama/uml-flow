import type { Diagram, DiagramNode, Edge } from "@uml-editor/shared";

function mapToPrismaType(rawType: string): string {
  const t = (rawType || "string").toLowerCase().trim();
  if (t === "int" || t === "integer" || t === "serial" || t === "smallint") return "Int";
  if (t === "bigint" || t === "long" || t === "i64") return "BigInt";
  if (t === "float" || t === "double" || t === "real") return "Float";
  if (t === "decimal" || t === "numeric") return "Decimal";
  if (t === "bool" || t === "boolean") return "Boolean";
  if (t === "date" || t === "datetime" || t === "timestamp") return "DateTime";
  if (t === "json" || t === "jsonb") return "Json";
  if (t === "bytes" || t === "blob") return "Bytes";
  return "String";
}

function toPascal(str: string): string {
  return str
    .replace(/(?:^\w|[A-Z]|\b\w)/g, (letter) => letter.toUpperCase())
    .replace(/[\s_-]+/g, "");
}

function toCamel(str: string): string {
  const p = toPascal(str);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

/**
 * Generate official Prisma schema (`schema.prisma`) from ERD or Class Diagram
 */
export function generatePrisma(diagram: Diagram): string {
  const entities = (diagram.nodes || []).filter(
    (n) => (n.type as string) !== "note" && (n.type as string) !== "system" && (n.type as string) !== "boundary"
  );

  let out = `// ------------------------------------------------------------------------------\n`;
  out += `// Prisma Schema generated by UML Flow\n`;
  out += `// Diagram: ${diagram.name || "DatabaseSchema"} (${diagram.type})\n`;
  out += `// Generated At: ${new Date().toISOString()}\n`;
  out += `// ------------------------------------------------------------------------------\n\n`;

  out += `datasource db {\n`;
  out += `  provider = "postgresql"\n`;
  out += `  url      = env("DATABASE_URL")\n`;
  out += `}\n\n`;

  out += `generator client {\n`;
  out += `  provider = "prisma-client-js"\n`;
  out += `}\n\n`;

  // Render Enums first
  const enumNodes = entities.filter((n) => (n.type as string) === "enum");
  for (const en of enumNodes) {
    const enumName = toPascal(en.name);
    out += `enum ${enumName} {\n`;
    const attrs = (en as any).attributes || [];
    for (const attr of attrs) {
      const val = (attr.name || attr).toString().toUpperCase().replace(/[^A-Z0-9_]/g, "_");
      out += `  ${val}\n`;
    }
    out += `}\n\n`;
  }

  // Render Models
  const modelNodes = entities.filter((n) => (n.type as string) !== "enum");
  const modelNames = new Set(modelNodes.map((n) => toPascal(n.name)));

  for (const model of modelNodes) {
    const modelName = toPascal(model.name);
    out += `model ${modelName} {\n`;

    const attrs = (model as any).attributes || [];
    let hasId = false;

    for (const attr of attrs) {
      const fieldName = toCamel(attr.name || "field");
      let typeStr = mapToPrismaType(attr.type);

      // Check if type references an existing enum or model
      for (const en of enumNodes) {
        if (en.name.toLowerCase() === (attr.type || "").toLowerCase()) {
          typeStr = toPascal(en.name);
          break;
        }
      }

      const isPk = attr.isPrimaryKey || fieldName === "id";
      const isUnique = attr.isUnique && !isPk;
      const isNullable = attr.isNullable && !isPk;

      let fieldLine = `  ${fieldName.padEnd(16)} ${typeStr}${isNullable ? "?" : ""}`;

      if (isPk) {
        hasId = true;
        if (typeStr === "Int" || typeStr === "BigInt") {
          fieldLine += " @id @default(autoincrement())";
        } else if (fieldName.includes("uuid") || typeStr === "String") {
          fieldLine += " @id @default(uuid())";
        } else {
          fieldLine += " @id";
        }
      } else if (isUnique) {
        fieldLine += " @unique";
      }

      if (/created_?at/i.test(fieldName)) {
        fieldLine += " @default(now())";
      } else if (/updated_?at/i.test(fieldName)) {
        fieldLine += " @updatedAt";
      }

      out += `${fieldLine}\n`;
    }

    // Default primary key fallback if missing
    if (!hasId && attrs.length === 0) {
      out += `  id               Int      @id @default(autoincrement())\n`;
      out += `  createdAt        DateTime @default(now())\n`;
    }

    // Relation fields from edges
    const incomingEdges = (diagram.edges || []).filter((e) => e.target === model.id);
    const outgoingEdges = (diagram.edges || []).filter((e) => e.source === model.id);

    // One-to-many children list
    for (const edge of outgoingEdges) {
      const targetNode = modelNodes.find((n) => n.id === edge.target);
      if (targetNode && targetNode.id !== model.id) {
        const targetModelName = toPascal(targetNode.name);
        const relPropName = toCamel(targetModelName) + "s";
        out += `  ${relPropName.padEnd(16)} ${targetModelName}[]\n`;
      }
    }

    // Many-to-one parent reference
    for (const edge of incomingEdges) {
      const parentNode = modelNodes.find((n) => n.id === edge.source);
      if (parentNode && parentNode.id !== model.id) {
        const parentModelName = toPascal(parentNode.name);
        const relFieldName = toCamel(parentModelName);
        const fkFieldName = `${relFieldName}Id`;
        out += `  ${relFieldName.padEnd(16)} ${parentModelName} @relation(fields: [${fkFieldName}], references: [id])\n`;
        out += `  ${fkFieldName.padEnd(16)} Int\n`;
      }
    }

    out += `}\n\n`;
  }

  return out.trim() + "\n";
}
