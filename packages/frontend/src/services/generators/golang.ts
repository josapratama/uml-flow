import type { Diagram, ClassNode, ERDEntity } from "@uml-editor/shared";

function mapGoType(t: string): string {
  if (!t) return "string";
  const isOptional = t.endsWith("?");
  const base = isOptional ? t.slice(0, -1) : t;
  const lower = base.toLowerCase().trim();
  let mapped = "string";

  if (lower === "string" || lower === "varchar" || lower === "text") mapped = "string";
  else if (lower === "int" || lower === "integer" || lower === "serial") mapped = "int";
  else if (lower === "long" || lower === "bigint") mapped = "int64";
  else if (lower === "float") mapped = "float32";
  else if (lower === "double" || lower === "decimal" || lower === "numeric") mapped = "float64";
  else if (lower === "bool" || lower === "boolean") mapped = "bool";
  else if (lower === "datetime" || lower === "date" || lower === "timestamp") mapped = "time.Time";
  else if (lower === "guid" || lower === "uuid") mapped = "string";
  else if (lower === "void") mapped = "";
  else if (lower.endsWith("[]") || lower.startsWith("list<")) {
    const inner = lower.replace(/\[\]$/, "").replace(/^list<|>$/g, "");
    mapped = `[]${mapGoType(inner)}`;
  } else {
    mapped = base.charAt(0).toUpperCase() + base.slice(1);
  }

  return isOptional ? `*${mapped}` : mapped;
}

function toPascalCase(name: string): string {
  return (name || "Item")
    .replace(/[^a-zA-Z0-9_]/g, " ")
    .split(/[\s_]+/)
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function toSnakeCase(name: string): string {
  return (name || "item")
    .replace(/([a-z])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .toLowerCase();
}

/**
 * Generate Golang Structs & Interfaces from Class Diagram or ERD
 */
export function generateGolang(diagram: Diagram): string {
  const lines: string[] = [
    `// Code generated by UML Flow (Go Structs & Models Generator). DO NOT EDIT.`,
    `// Diagram: ${diagram.name || "Untitled"} (${diagram.type})`,
    `// Generated At: ${new Date().toISOString()}`,
    "",
    "package models",
    "",
    "import (",
    '    "time"',
    ")",
    "",
  ];

  if (diagram.type === "class") {
    const nodes = (diagram.nodes as ClassNode[]).filter(n => "name" in n);

    if (nodes.length === 0) {
      lines.push("// No classes found in diagram");
      return lines.join("\n");
    }

    // 1. Enums
    const enums = nodes.filter(n => n.type === "enum");
    for (const en of enums) {
      const typeName = toPascalCase(en.name);
      lines.push(`type ${typeName} string`);
      lines.push("");
      lines.push("const (");
      const attrs = en.attributes || [];
      if (attrs.length === 0) {
        lines.push(`    ${typeName}Default ${typeName} = "DEFAULT"`);
      } else {
        for (const a of attrs) {
          const val = a.name.trim();
          const constName = `${typeName}${toPascalCase(val)}`;
          lines.push(`    ${constName} ${typeName} = "${val}"`);
        }
      }
      lines.push(")");
      lines.push("");
    }

    // 2. Interfaces
    const interfaces = nodes.filter(n => n.type === "interface");
    for (const iface of interfaces) {
      const ifaceName = toPascalCase(iface.name);
      lines.push(`type ${ifaceName} interface {`);
      for (const m of iface.methods || []) {
        const methodName = toPascalCase(m.name);
        const params = ((m as any).parameters || m.params || [])
          .map((p: any) => `${p.name} ${mapGoType(p.type)}`)
          .join(", ");
        const retType = m.returnType ? mapGoType(m.returnType) : "";
        const retPart = retType ? ` ${retType}` : "";
        lines.push(`    ${methodName}(${params})${retPart}`);
      }
      lines.push("}");
      lines.push("");
    }

    // 3. Structs & Methods
    const classes = nodes.filter(n => n.type !== "enum" && n.type !== "interface");
    for (const cls of classes) {
      const structName = toPascalCase(cls.name);
      lines.push(`type ${structName} struct {`);
      for (const attr of cls.attributes || []) {
        const isOptional = attr.name.endsWith("?") || (attr.type && (attr.type.endsWith("?") || attr.type.toLowerCase().includes("optional")));
        const cleanName = attr.name.replace(/\?$/, "");
        const fieldName = toPascalCase(cleanName);
        let goType = mapGoType(attr.type || "string");
        if (isOptional && !goType.startsWith("*")) {
          goType = `*${goType}`;
        }
        const tagSnake = toSnakeCase(cleanName);
        const tag = `\`json:"${tagSnake}${isOptional ? ",omitempty" : ""}" db:"${tagSnake}"\``;
        lines.push(`    ${fieldName.padEnd(16)} ${goType.padEnd(14)} ${tag}`);
      }
      lines.push("}");
      lines.push("");

      // Methods
      for (const m of cls.methods || []) {
        const methodName = toPascalCase(m.name);
        const receiver = structName.charAt(0).toLowerCase();
        const params = ((m as any).parameters || m.params || [])
          .map((p: any) => `${p.name} ${mapGoType(p.type)}`)
          .join(", ");
        const retType = m.returnType ? mapGoType(m.returnType) : "";
        const retPart = retType ? ` ${retType}` : "";

        lines.push(`func (${receiver} *${structName}) ${methodName}(${params})${retPart} {`);
        if (retType === "bool") {
          lines.push("    return true");
        } else if (retType === "error") {
          lines.push("    return nil");
        } else if (retType === "int" || retType === "int64" || retType === "float64") {
          lines.push("    return 0");
        } else if (retType === "string") {
          lines.push('    return ""');
        } else if (retType) {
          lines.push("    return nil");
        }
        lines.push("}");
        lines.push("");
      }
    }
  } else if (diagram.type === "erd") {
    const entities = (diagram.nodes as ERDEntity[]).filter(n => "name" in n);

    if (entities.length === 0) {
      lines.push("// No entities found in ERD diagram");
      return lines.join("\n");
    }

    for (const ent of entities) {
      const structName = toPascalCase(ent.name);
      lines.push(`type ${structName} struct {`);
      for (const attr of ent.attributes || []) {
        const fieldName = toPascalCase(attr.name);
        const isNullable = Boolean(attr.isNullable || (attr as any).nullable);
        let goType = mapGoType(attr.type || "string");
        if (isNullable && !goType.startsWith("*")) {
          goType = `*${goType}`;
        }
        const tagSnake = toSnakeCase(attr.name);
        const tag = `\`json:"${tagSnake}${isNullable ? ",omitempty" : ""}" db:"${tagSnake}"\``;
        lines.push(`    ${fieldName.padEnd(16)} ${goType.padEnd(14)} ${tag}`);
      }
      lines.push("}");
      lines.push("");
    }
  } else {
    lines.push(`// Go export is only supported for Class and ERD diagrams.`);
  }

  return lines.join("\n");
}
