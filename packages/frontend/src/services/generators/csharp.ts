import type { Diagram, ClassNode, ERDEntity } from "@uml-editor/shared";

function mapCSharpType(t: string): string {
  if (!t) return "string";
  const isNullable = t.endsWith("?");
  const base = isNullable ? t.slice(0, -1) : t;
  const lower = base.toLowerCase().trim();
  let mapped = "string";
  if (lower === "string" || lower === "varchar" || lower === "text") mapped = "string";
  else if (lower === "int" || lower === "integer" || lower === "number" || lower === "serial") mapped = "int";
  else if (lower === "long" || lower === "bigint") mapped = "long";
  else if (lower === "float") mapped = "float";
  else if (lower === "double") mapped = "double";
  else if (lower === "decimal" || lower === "numeric" || lower === "money") mapped = "decimal";
  else if (lower === "bool" || lower === "boolean") mapped = "bool";
  else if (lower === "date") mapped = "DateOnly";
  else if (lower === "datetime" || lower === "timestamp") mapped = "DateTime";
  else if (lower === "guid" || lower === "uuid") mapped = "Guid";
  else if (lower === "void") mapped = "void";
  else if (lower.endsWith("[]") || lower.startsWith("list<")) {
    const inner = lower.replace(/\[\]$/, "").replace(/^list<|>$/g, "");
    mapped = `List<${mapCSharpType(inner)}>`;
  } else {
    mapped = base;
  }
  return isNullable ? `${mapped}?` : mapped;
}

function sanitizeIdentifier(name: string): string {
  const clean = (name || "Unnamed").replace(/[^a-zA-Z0-9_]/g, "_");
  // Capitalize first letter for C# PascalCase
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}

function toPascalCase(str: string): string {
  return (str || "Property")
    .replace(/[^a-zA-Z0-9_]/g, " ")
    .split(/[\s_]+/)
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function getDefaultValue(csType: string, isNullable: boolean): string {
  if (isNullable) return " = null;";
  if (csType === "string") return ' = string.Empty;';
  if (csType.startsWith("List<")) return " = new();";
  if (csType === "bool") return " = false;";
  if (csType === "int" || csType === "long" || csType === "float" || csType === "double" || csType === "decimal") return " = 0;";
  if (csType === "DateTime") return " = DateTime.UtcNow;";
  if (csType === "Guid") return " = Guid.NewGuid();";
  return "";
}

/**
 * Generate C# (.NET 8 / C# 12) Entity Classes from Class Diagram or ERD
 */
export function generateCSharp(diagram: Diagram): string {
  const lines: string[] = [
    "// ------------------------------------------------------------------------------",
    `// <auto-generated>`,
    `//     Generated by UML Flow (.NET 8 / C# 12 POCO & Entity Generator)`,
    `//     Diagram: ${diagram.name || "Untitled"} (${diagram.type})`,
    `//     Generated At: ${new Date().toISOString()}`,
    `// </auto-generated>`,
    "// ------------------------------------------------------------------------------",
    "",
    "using System;",
    "using System.Collections.Generic;",
    "using System.ComponentModel.DataAnnotations;",
    "using System.ComponentModel.DataAnnotations.Schema;",
    "",
    "namespace App.Domain.Entities",
    "{",
  ];

  if (diagram.type === "class") {
    const nodes = (diagram.nodes as ClassNode[]).filter(n => "name" in n);

    if (nodes.length === 0) {
      lines.push("    // No class nodes found in this diagram.");
      lines.push("}");
      return lines.join("\n");
    }

    for (const node of nodes) {
      const className = sanitizeIdentifier(node.name);

      // Handle Enum
      if (node.type === "enum") {
        lines.push(`    public enum ${className}`);
        lines.push("    {");
        const attrs = node.attributes || [];
        if (attrs.length === 0) {
          lines.push("        None = 0,");
        } else {
          for (let i = 0; i < attrs.length; i++) {
            const attr = attrs[i];
            const enumName = toPascalCase(attr.name);
            lines.push(`        ${enumName} = ${i},`);
          }
        }
        lines.push("    }");
        lines.push("");
        continue;
      }

      // Handle Interface
      if (node.type === "interface") {
        const ifaceName = className.startsWith("I") ? className : `I${className}`;
        lines.push(`    public interface ${ifaceName}`);
        lines.push("    {");
        for (const attr of node.attributes || []) {
          const csType = mapCSharpType(attr.type || "string");
          const propName = toPascalCase(attr.name);
          lines.push(`        ${csType} ${propName} { get; set; }`);
        }
        for (const m of node.methods || []) {
          const returnType = mapCSharpType(m.returnType || "void");
          const methodName = toPascalCase(m.name);
          const params = (m.parameters || [])
            .map(p => `${mapCSharpType(p.type)} ${p.name}`)
            .join(", ");
          lines.push(`        ${returnType} ${methodName}(${params});`);
        }
        lines.push("    }");
        lines.push("");
        continue;
      }

      // Handle Inheritance / Realization
      const inheritanceEdges = diagram.edges.filter(
        e => e.source === node.id && (e.type === "inheritance" || e.type === "realization")
      );
      const parentTypes = inheritanceEdges
        .map(e => {
          const targetNode = nodes.find(n => n.id === e.target);
          if (!targetNode) return "";
          if (targetNode.type === "interface") {
            const base = sanitizeIdentifier(targetNode.name);
            return base.startsWith("I") ? base : `I${base}`;
          }
          return sanitizeIdentifier(targetNode.name);
        })
        .filter(Boolean);

      const isAbstract = node.type === "abstract";
      const classModifier = isAbstract ? "public abstract class" : "public class";
      const inheritanceSuffix = parentTypes.length > 0 ? ` : ${parentTypes.join(", ")}` : "";

      lines.push(`    ${classModifier} ${className}${inheritanceSuffix}`);
      lines.push("    {");

      // Attributes / Properties
      const attrs = node.attributes || [];
      if (attrs.length === 0 && (!node.methods || node.methods.length === 0)) {
        lines.push("        // No properties or methods defined");
      }

      for (const attr of attrs) {
        const isOptional = attr.name.endsWith("?") || (attr.type && (attr.type.endsWith("?") || attr.type.toLowerCase().includes("optional")));
        const cleanName = attr.name.replace(/\?$/, "");
        const propName = toPascalCase(cleanName);
        let csType = mapCSharpType(attr.type || "string");
        if (isOptional && !csType.endsWith("?")) {
          csType = `${csType}?`;
        }

        const visibility = attr.visibility === "private" ? "private" : attr.visibility === "protected" ? "protected" : "public";
        const defaultVal = getDefaultValue(csType.replace(/\?$/, ""), Boolean(isOptional));

        lines.push(`        ${visibility} ${csType} ${propName} { get; set; }${defaultVal}`);
      }

      // Methods
      const methods = node.methods || [];
      if (methods.length > 0) {
        lines.push("");
        for (const m of methods) {
          const returnType = mapCSharpType(m.returnType || "void");
          const methodName = toPascalCase(m.name);
          const visibility = m.visibility === "private" ? "private" : m.visibility === "protected" ? "protected" : "public";
          const params = (m.parameters || [])
            .map(p => `${mapCSharpType(p.type)} ${p.name}`)
            .join(", ");

          if (isAbstract) {
            lines.push(`        ${visibility} abstract ${returnType} ${methodName}(${params});`);
          } else {
            lines.push(`        ${visibility} virtual ${returnType} ${methodName}(${params})`);
            lines.push("        {");
            if (returnType === "void") {
              lines.push("            // Implementation logic");
            } else if (returnType === "bool") {
              lines.push("            return false;");
            } else if (returnType === "int" || returnType === "long" || returnType === "double" || returnType === "decimal") {
              lines.push("            return 0;");
            } else {
              lines.push("            throw new NotImplementedException();");
            }
            lines.push("        }");
          }
        }
      }

      lines.push("    }");
      lines.push("");
    }
  } else if (diagram.type === "erd") {
    // Generate C# EF Core Entity POCOs
    const entities = (diagram.nodes as ERDEntity[]).filter(n => "name" in n);

    if (entities.length === 0) {
      lines.push("    // No ERD entities found in this diagram.");
      lines.push("}");
      return lines.join("\n");
    }

    for (const entity of entities) {
      const className = toPascalCase(entity.name);
      const tableName = entity.name.toLowerCase();

      lines.push(`    [Table("${tableName}")]`);
      lines.push(`    public class ${className}`);
      lines.push("    {");

      const attrs = entity.attributes || [];
      for (const attr of attrs) {
        const propName = toPascalCase(attr.name);
        const csType = mapCSharpType(attr.type || "string");
        const isNullable = Boolean(attr.nullable);
        const effectiveType = isNullable && !csType.endsWith("?") ? `${csType}?` : csType;

        if (attr.pk) {
          lines.push("        [Key]");
          if (csType === "int" || csType === "long") {
            lines.push("        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]");
          }
        } else if (!isNullable && csType === "string") {
          lines.push("        [Required]");
        }

        if (attr.fk) {
          lines.push(`        [ForeignKey(nameof(${propName}))]`);
        }

        const defaultVal = getDefaultValue(csType, isNullable);
        lines.push(`        public ${effectiveType} ${propName} { get; set; }${defaultVal}`);
      }

      lines.push("    }");
      lines.push("");
    }
  } else {
    lines.push(`    // C# export is not supported for diagram type: ${diagram.type}`);
  }

  lines.push("}");
  return lines.join("\n");
}
